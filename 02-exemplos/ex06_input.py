# Exemplo 06 — Entrada de dados com input
# Objetivo: perguntar algo ao usuário e usar a resposta na saída.

# input() mostra a pergunta e espera o usuário digitar e pressionar Enter.
# O que foi digitado fica guardado com o nome "nome".
nome = input("Qual é o seu nome? ")

# Repare: nome SEM aspas mostra o que foi digitado.
print("Olá,", nome)

# Com aspas, aparece literalmente a palavra "nome".
print("Isto é a palavra:", "nome")
