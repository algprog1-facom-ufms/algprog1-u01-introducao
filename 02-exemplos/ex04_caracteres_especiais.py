# Exemplo 04 — Caracteres especiais
# Objetivo: usar \n (nova linha), \t (tabulação) e aspas dentro de textos.

# \n quebra a linha dentro de um único texto.
print("Linha 1\nLinha 2\nLinha 3")

print()

# \t insere uma tabulação, útil para alinhar informações.
print("Nome:\tAna")
print("Curso:\tSistemas de Informação")

print()

# Para usar aspas duplas dentro do texto, use \" ...
print("O professor disse: \"Bem-vindos!\"")
# ... ou delimite o texto com aspas simples.
print('A aluna respondeu: "Obrigada!"')
